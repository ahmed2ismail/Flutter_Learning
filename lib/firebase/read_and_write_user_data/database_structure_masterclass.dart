============================= الدليل الشامل لهيكلة قواعد البيانات وهندسة التطبيقات =============================
==================================================================================================

مرحباً بك يا صديقي. في هذا الملف، سنأخذك في رحلة من الصفر وحتى الاحتراف لفهم قواعد البيانات، 
كيفية هيكلة بيانات تطبيقك، الفرق بين SQL و NoSQL، وكيفية كتابة كود مرن يسمح لك بتغيير 
قاعدة البيانات (مثلاً من Firebase إلى Supabase) في ثانية واحدة دون تدمير تطبيقك.

--------------------------------------------------------------------------------------------------
أولاً: ما هو الـ Database Structure (أو Data Structure) الخاص بالتطبيق؟
--------------------------------------------------------------------------------------------------

تخيل أنك تفتح مكتبة (Bookly App) أو متجر فواكه (Fruits Hub). 
قبل أن تبني الأرفف وتضع المنتجات، يجب أن تسأل نفسك:
- أين سأضع الفواكه؟
- كيف سأسجل بيانات العملاء؟
- إذا اشترى عميل فاكهة، كيف سأربط الفاتورة بالعميل وبالفاكهة؟

هذا التفكير على الورق هو الـ "Data Structure". 
هو عملية تحديد "الكيانات" (Entities) الموجودة في تطبيقك، وما هي خصائص كل كيان، وكيف ترتبط ببعضها.

مثال تطبيقي (Fruits Hub App):
1. كيان المستخدم (User): لديه (ID، اسم، إيميل، عنوان، رقم هاتف).
2. كيان المنتج (Product): لديه (ID، اسم، صورة، سعر، الكمية المتاحة، ID_القسم).
3. كيان القسم (Category): لديه (ID، اسم القسم).
4. كيان الطلب (Order): لديه (ID، ID_المستخدم، تاريخ الطلب، السعر الإجمالي، المنتجات المشتراة).

كيفية تخزين هذه الكيانات وربطها ببعضها هو ما نسميه "Database Structure".

--------------------------------------------------------------------------------------------------
ثانياً: المعركة الكبرى (SQL مقابل NoSQL)
--------------------------------------------------------------------------------------------------

قواعد البيانات تنقسم إلى عائلتين كبيرتين، يجب أن تفهم الفرق بينهما لتعرف متى تختار أياً منهما.

تصحيح معلومة: Firebase تدعم NoSQL فقط (عبر Firestore أو Realtime DB).
أما Supabase فهي تعتمد على PostgreSQL وهي قاعدة بيانات SQL.

================ 1. قواعد بيانات SQL (Relational Databases) ================
- الفكرة: تشبه جداول برنامج Excel. بيانات منظمة جداً، كل جدول (Table) له أعمدة ثابتة (Columns).
- القواعد: صارمة (Strict Schema). لا يمكنك إضافة منتج بدون سعر إذا كان عمود السعر إجبارياً.
- العلاقات: قوية جداً. نربط الجداول ببعضها باستخدام الـ ID (يسمى Foreign Key).
- أمثلة على خدمات/برامج: MySQL, PostgreSQL, SQLite, Supabase.

أمــــثـــلـــة SQL (متدرجة الصعوبة):

* [مستوى سهل] جدول المستخدمين (Users Table):
ID   | Name    | Email
---------------------------------
1    | Ahmed   | ahmed@gmail.com
2    | Ali     | ali@gmail.com

* [مستوى متوسط] جدول المنتجات (Products Table):
ID   | Name    | Price | Category_ID  (هذا يربط المنتج بجدول الأقسام)
---------------------------------------
101  | Apple   | 5.0   | 10          (نفهم من 10 أنه قسم الفواكه مثلاً)
102  | Carrot  | 3.0   | 20          (نفهم من 20 أنه قسم الخضروات)

* [مستوى احترافي] جدول الطلبات (Orders Table) وعلاقة Many-to-Many:
لو عميل اشترى عدة منتجات، ننشئ جدولاً للطلب، وجدولاً وسيطاً (Order_Items) لمعرفة ماذا اشترى:
Order_ID | User_ID | Date
-------------------------
500      | 1       | 2024-01-01

Order_ID | Product_ID | Quantity
--------------------------------
500      | 101        | 2 كيلو
500      | 102        | 1 كيلو
(في SQL، نقوم بعمل استعلام يسمى JOIN لجلب بيانات العميل، مع الطلب، مع أسماء المنتجات معاً).


================ 2. قواعد بيانات NoSQL (Non-Relational Databases) ================
- الفكرة: تشبه المجلدات (Folders) والملفات النصية (JSON Files). 
  لا يوجد جداول، بل يوجد مجموعات (Collections) وبيكون ليها اسم وبيتخزن بداخلها وثائق (Documents) وكل Document عبارة عن Map {'key': 'value'}.
- القواعد: مرنة جداً (Schemaless). يمكنك أن تضع في وثيقة عميل رقم هاتفه، ووثيقة عميل آخر لا تضع فيها رقم هاتف، ولن يعترض النظام.
- العلاقات: ضعيفة. بدلاً من الجداول الوسيطة، نقوم بعملية تسمى "النسخ المتكرر" (Denormalization).
- أمثلة على خدمات/برامج: MongoDB, Firebase Firestore, Firebase Realtime DB.

أمــــثـــلـــة NoSQL في Firebase Firestore (متدرجة الصعوبة):

* [مستوى سهل] مجموعة المستخدمين (Users Collection):
الوثيقة (Document) التي تحمل ID: 1
{
  "name": "Ahmed",
  "email": "ahmed@gmail.com"
}

* [مستوى متوسط] مجموعة فرعية (Sub-collection):
في NoSQL، يمكن أن يكون داخل وثيقة المستخدم مجموعة فرعية خاصة بطلباته هو فقط:
Users (Collection)
   -> Document (ID: 1)
        -> Orders (Sub-collection)
             -> Document (Order 500)
                  { "date": "2024-01-01", "total": 150 }

* [مستوى احترافي] مشكلة الـ Denormalization (تكرار البيانات المتعمد):
في الـ SQL كنا نخزن Product_ID فقط في الطلب. 
في الـ NoSQL (مثل Firebase)، لو خزنّا الـ ID فقط، سنضطر لقراءة وثيقة الطلب، ثم قراءة وثيقة المنتج لنجلب اسمه (وهذا يكلف أموالاً في Firebase لأن المحاسبة بعدد القراءات Reads).
الحل الاحترافي في NoSQL؟ ننسخ البيانات!
Document (Order 500):
{
  "date": "2024-01-01",
  "total": 150,
  "products": [
     { "id": "101", "name": "Apple", "price": 5.0, "quantity": 2 },
     { "id": "102", "name": "Carrot", "price": 3.0, "quantity": 1 }
  ]
}
لاحظ أننا نسخنا (اسم وسعر) المنتج داخل الطلب. لماذا؟ لكي نقرأ الطلب بـ Read واحد فقط من Firebase!


--------------------------------------------------------------------------------------------------
ثالثاً: كيف تختار بين SQL و NoSQL لتطبيقك؟
--------------------------------------------------------------------------------------------------

اختر SQL (مثل Supabase أو API خاص بـ Laravel/NodeJS) إذا:
1. كانت بياناتك مترابطة جداً ومعقدة (تطبيق محاسبة، نظام بنكي، تطبيق إدارة مستشفيات).
2. كنت تحتاج لتقارير معقدة (مثلاً: "جلب كل المستخدمين الذين اشتروا تفاح في آخر 3 أشهر ودفعوا بفيزا").

اختر NoSQL (مثل Firebase) إذا:
1. كان تطبيقك يحتاج لتحديثات بالوقت الفعلي (Real-time) مثل تطبيقات الدردشة (Chat) أو تتبع السائق (Delivery).
2. كانت بنية البيانات قابلة للتغيير باستمرار وتفضل المرونة والسرعة في التطوير (Startups).
3. البيانات غير مترابطة بشدة (أغلب عمليات القراءة تكون لقائمة منتجات، أو تفاصيل مستخدم).

* تطبيق Fruits Hub: يمكن بناءه بالنوعين، لكن Firebase ممتاز لسرعة إنجازه.
* تطبيق Bookly: Firebase ممتاز له جداً.

--------------------------------------------------------------------------------------------------
رابعاً: السر الأعظم (كيف أكتب كوداً يسمح لي بالانتقال من Firebase إلى Supabase بسهولة؟)
--------------------------------------------------------------------------------------------------

هنا يأتي دور الـ "Clean Architecture" ومبدأ هام يسمى "Dependency Inversion" (عكس الاعتماديات).

المشكلة الشائعة للمبتدئين:
يقوم المبتدئ بكتابة كود Firebase مباشرة داخل زر الـ Login أو داخل صفحة الـ UI:
FirebaseFirestore.instance.collection('users').add({...})
إذا أراد التغيير إلى Supabase، سيضطر للمرور على 100 صفحة في التطبيق لتعديل الكود! هذا كابوس.

الحل الاحترافي (Repository Pattern):
نحن لا نجعل الـ UI يتحدث مع Firebase أبداً. ولا حتى الـ Bloc/Cubit.
نحن نقوم بإنشاء "عقد" (Contract/Interface) في طبقة الـ Domain، ثم ننفذه في طبقة الـ Data.

الخطوة 1: في طبقة الـ Domain (قلب التطبيق)، نكتب الـ Contract (العقد) في مجلد ال repos في ملف ال featureName_repo.dart زي auth_repo.dart:

```dart
abstract class IUserRepository {
  // أقول "ماذا" أريد أن أفعل، ولا يهمني "كيف" سيتم ذلك
  Future<void> saveUserData(UserEntity user);
  Future<UserEntity> getUserData(String userId);
}
```

الخطوة 2: في طبقة الـ Data، نكتب الـ Implementation (التنفيذ) لـ Firebase ويكتب في مجلد الـ data/repos في ملف الـ featureName_repo_impl.dart زي auth_repo_impl.dart:

```dart
class FirebaseUserRepositoryImpl implements IUserRepository {
  final FirebaseFirestore firestore;
  FirebaseUserRepositoryImpl(this.firestore);

  @override
  Future<void> saveUserData(UserEntity user) async {
     // هنا نكتب كود فايربيز بالتفصيل
     await firestore.collection('users').doc(user.id).set(user.toMap());
  }
  // ... باقي الدوال
}
```

الخطوة 3: في طبقة الـ Presentation (الـ Cubit مثلاً):
الـ Cubit لا يعرف إن كنا نستخدم Firebase أو شيء آخر. هو يعرف فقط `IUserRepository`.

```dart
class UserCubit extends Cubit<UserState> {
  final IUserRepository userRepository; // يعتمد على العقد، وليس فايربيز

  UserCubit(this.userRepository) : super(UserInitial());

  Future<void> saveUser(UserEntity user) async {
     await userRepository.saveUserData(user); // الكيوبت يطلب الحفظ فقط
  }
}
```

الخطوة 4: (لحظة السحر!) في ملف حقن الاعتماديات (Dependency Injection) باستخدام GetIt:

```dart
// في ملف injection_container.dart
sl.registerLazySingleton<IUserRepository>(() => FirebaseUserRepositoryImpl(sl()));
```

كيف أنتقل من Firebase إلى Supabase الآن؟
1. أترك طبقة الـ Domain كما هي (لا نلمسها).
2. أترك طبقة الـ Presentation والـ Cubits كما هي (لا نلمسها).
3. أنشئ كلاس جديد فقط في طبقة الـ Data:

```dart
class SupabaseUserRepositoryImpl implements IUserRepository {
  final SupabaseClient supabase;
  SupabaseUserRepositoryImpl(this.supabase);

  @override
  Future<void> saveUserData(UserEntity user) async {
     // هنا نكتب كود Supabase
     await supabase.from('users').insert(user.toMap());
  }
}
```

4. أذهب إلى ملف `injection_container.dart` وأغير سطراً واحداً فقط:
```dart
// السطر القديم:
// sl.registerLazySingleton<IUserRepository>(() => FirebaseUserRepositoryImpl(sl()));

// السطر الجديد:
sl.registerLazySingleton<IUserRepository>(() => SupabaseUserRepositoryImpl(sl()));
```
مبروك! تطبيقك بالكامل الآن يعمل على Supabase بدلاً من Firebase بتغيير سطر واحد فقط!
هذه هي قوة الـ Clean Architecture الحقيقية.

--------------------------------------------------------------------------------------------------
خامساً: كيف تبني الـ Data Structure الخاص بتطبيقك قبل كتابة سطر كود واحد؟
--------------------------------------------------------------------------------------------------

لتحديد هيكل البيانات لتطبيق مثل Fruits Hub، قم بإحضار ورقة وقلم واتبع الخطوات:

1. تحديد الـ Entities (الكيانات):
اسأل نفسك: من هم الأبطال في تطبيقي؟
- العميل (User)
- المنتج/الفاكهة (Product)
- السلة (Cart)
- الطلب النهائي (Order)

2. تحديد الـ Attributes (الخصائص):
- العميل: سيحتاج (ID، اسم، إيميل، عنوان التوصيل، هل هو موقوف أم لا؟).
- المنتج: سيحتاج (ID، اسم الفاكهة، الصورة، السعر للكيلو، الوصف، التقييم، ID_القسم).

3. تحديد الـ Relationships (العلاقات):
- العميل لديه سلة واحدة (One-to-One).
- القسم (فواكه استوائية) يحتوي على عدة منتجات (One-to-Many).
- الطلب يحتوي على عدة منتجات، والمنتج يمكن أن يكون في عدة طلبات (Many-to-Many).

4. ترجمة هذا إلى (Firebase Firestore) - NoSQL Approach:
في فايربيز، لا نصنع جدولاً للـ Cart وجدولاً للـ User ونجعل بينهما علاقة. 
لتقليل تكلفة القراءات (Reads)، نفكر في "الشاشة التي سيراها المستخدم".

- مجموعة المستخدمين `users` (Collection):
  وثيقة (Document): `user_id_123`
  المحتوى:
  {
     "name": "Ahmed",
     "email": "ahmed@test.com",
     "addresses": [ "القاهرة، شارع 1", "الجيزة، شارع 2" ], // مصفوفة لتجنب إنشاء كوليكشن جديد
     "cart": [
        {"product_id": "apple_1", "quantity": 2, "price": 10},
        {"product_id": "banana_2", "quantity": 1, "price": 5}
     ] // وضعنا السلة داخل المستخدم لنجلب بياناته وسلته بطلب واحد من السيرفر! (Denormalization)
  }

- مجموعة المنتجات `products` (Collection):
  وثيقة (Document): `apple_1`
  المحتوى:
  {
     "name": "Apple",
     "price": 10,
     "category": "Fruits",
     "image_url": "https://..."
  }

نصيحة ذهبية: في الـ NoSQL، صمم قاعدة بياناتك بناءً على "كيف ستقرأ الشاشات البيانات" (Design for the View). 
بينما في الـ SQL، نصمم قاعدة البيانات بناءً على "كيف ترتبط البيانات ببعضها رياضياً" (Design for the Data).

